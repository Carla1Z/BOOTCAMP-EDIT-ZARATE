from calculadora import sumar as sum, restar as sub, multiplicar as mul, dividir as div

print(sum(1, 2))
print(sub(1, 2))
print(mul(1, 2))
print(div(1, 2))

# el import * es una forma de importar todos los atributos y metodos de un modulo.
# en este caso, podemos usar sum, sub, mul y div en lugar de sumar, restar, multiplicar y dividir.
# esto es mas conveniente que importar el modulo completo y luego usar los atributos y metodos como calculadora.PI, calculadora.sumar, etc. 