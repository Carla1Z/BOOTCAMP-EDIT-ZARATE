import calculadora

# Varios ejemplos de uso del módulo calculadora     
# 1. Imprimir el valor de PI
print(calculadora.PI)
# 2. Sumar dos números
print(calculadora.sumar(1, 2))
# 3. Restar dos números
print(calculadora.restar(1, 2))
# 4. Multiplicar dos números
print(calculadora.multiplicar(1, 2))
# 5. Dividir dos números
print(calculadora.dividir(1, 2))

# parece como si el modulo calculadora fuera un objeto,
# tiene un monton de atributos y metodos que podemos usar.